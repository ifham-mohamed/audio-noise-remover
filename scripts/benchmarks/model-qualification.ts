import { z } from "zod";
import { createHash } from "node:crypto";
import { openSync, readSync, closeSync } from "node:fs";
import { resolve } from "node:path";

const text = z.string().trim().min(1);
const number = z.number().finite();
const positive = number.positive();
const count = number.int().nonnegative();
const hash = z.string().regex(/^[a-f0-9]{64}$/);
const ids = z.array(text).min(1);
const evidence = z.strictObject({ id: text, path: text, sha256: hash });
const rights = z.strictObject({
  license: text, noticeEvidence: text, attribution: text, reviewer: text,
  reviewEvidence: text, evaluationAllowed: z.boolean(), productionUseAllowed: z.boolean(),
});
const declaration = z.strictObject({
  status: z.enum(["verified", "unknown", "overlap"]), reviewer: text,
  method: text, evidenceIds: ids,
});
const metrics = z.strictObject({
  stoiBefore: number.min(0).max(1).optional(), stoiAfter: number.min(0).max(1).optional(),
  siSdrBeforeDb: number.optional(), siSdrAfterDb: number.optional(),
  pesqBefore: number.min(-0.5).max(4.5).optional(), pesqAfter: number.min(-0.5).max(4.5).optional(),
  introducedClippedSamples: count.optional(), encodedTruePeakDbtp: number.optional(),
  integratedLufs: number.optional(), targetLufs: number.optional(),
  durationValid: z.boolean().optional(), channelsValid: z.boolean().optional(),
  encodedArtifactValid: z.boolean().optional(), sourceUnchanged: z.boolean().optional(),
});

/** Evidence is an attested local measurement, never generated by this evaluator. */
export const qualificationManifestSchema = z.strictObject({
  schemaVersion: z.literal(1), runId: text, purpose: z.enum(["private-diagnostic", "production-qualification"]),
  evidence: z.array(evidence).min(1),
  model: z.strictObject({ id: text, revision: text, artifactEvidence: text,
    conversion: text, conversionEvidence: text, rights }),
  datasets: z.array(z.strictObject({ id: text, revision: text, source: text,
    representation: text, split: text, roles: z.array(z.enum(["speech", "noise"])).min(1), rights })).min(1),
  independence: z.strictObject({
    evaluation: declaration,
    training: z.strictObject({ corpora: ids, sources: declaration, speakers: declaration, noise: declaration }),
  }),
  protocol: z.strictObject({
    seed: count, selection: text, preprocessing: text, alignment: text,
    metricImplementations: z.record(text, z.strictObject({ name: text, version: text, evidenceId: text })), metricRights: rights,
    profile: text, targetLufs: number, profileEvidence: text, preregistrationEvidence: text,
    minimumNoisyClips: positive.int(), minimumCleanClips: positive.int(),
    minimumSpeakers: positive.int(), minimumNoiseSources: positive.int(),
    requiredNoiseClasses: ids,
    acceptance: z.strictObject({ reviewEvidence: text, maximumRtf: positive,
      maximumPeakMemoryMb: positive, maximumColdLoadMs: positive,
      maximumCancellationMs: positive, minimumListeners: positive.int(), minimumTrials: positive.int() }),
  }),
  clips: z.array(z.strictObject({
    id: text, kind: z.enum(["noisy", "clean"]), speaker: text,
    speechDataset: text, noiseDataset: text.optional(), noiseSource: text.optional(), noiseClass: text.optional(),
    sourceEvidence: ids, measurementEvidence: text, outputEvidence: text,
    startSample: count, lengthSamples: positive.int(), sampleRateHz: positive.int(),
    noiseStartSample: count.optional(), mixtureGain: positive.optional(), snrDb: number.optional(), metrics,
  })).min(1),
  runtime: z.array(z.strictObject({
    platform: z.enum(["windows", "macos", "linux"]), machine: text, browser: text,
    runtimeVersion: text, provider: z.literal("cpu"), threads: positive.int(), evidenceIds: ids,
    actualMedia: z.boolean(), appPath: z.boolean(), coldStartOffline: z.boolean(),
    warmRtf: z.array(number.nonnegative()).min(1), coldLoadMs: number.nonnegative(),
    peakMemoryMb: positive, cancellationMs: number.nonnegative(), cleanupVerified: z.boolean(),
  })).optional(),
  listening: z.strictObject({
    blinded: z.boolean(), randomized: z.boolean(), loudnessMatched: z.boolean(), protocolEvidence: text,
    trials: z.array(z.strictObject({ listener: text, clipId: text, evidenceId: text,
      speechDamage: z.boolean(), unacceptableArtifacts: z.boolean() })).min(1),
  }).optional(),
});

export type QualificationManifest = z.infer<typeof qualificationManifestSchema>;
type Gate = { id: string; status: "pass" | "fail" | "missing"; detail: string; value?: number };
const gateIds = ["manifest", "evidence", "rights", "independence", "coverage", "stoi", "si-sdr", "pesq-clean",
  "clipping", "loudness", "output-integrity", "runtime", "memory", "listening"];

// Stream hashes so existing local corpora do not need to fit in memory.
export function fileSha256(path: string): string {
  const digest = createHash("sha256");
  const buffer = Buffer.alloc(1024 * 1024);
  const fd = openSync(path, "r");
  try { let size; while ((size = readSync(fd, buffer, 0, buffer.length, null)) > 0) digest.update(buffer.subarray(0, size)); }
  finally { closeSync(fd); }
  return digest.digest("hex");
}
export function median(values: number[]): number {
  if (!values.length || values.some((value) => !Number.isFinite(value))) throw new Error("finite nonempty values required");
  const sorted = [...values].sort((a, b) => a - b);
  const middle = Math.floor(sorted.length / 2);
  return sorted.length % 2 ? sorted[middle] : (sorted[middle - 1] + sorted[middle]) / 2;
}

/** Without an actual evidence verifier the report cannot qualify. Paths are relative to the manifest. */
export function evaluateQualification(input: unknown, verify?: (item: z.infer<typeof evidence>) => boolean) {
  const parsed = qualificationManifestSchema.safeParse(input);
  const gates: Gate[] = [];
  const put = (id: string, status: Gate["status"], detail: string, value?: number) => gates.push({ id, status, detail, ...(value === undefined ? {} : { value }) });
  const check = (id: string, passed: boolean, detail: string, value?: number) => put(id, passed ? "pass" : "fail", detail, value);
  if (!parsed.success) {
    put("manifest", "fail", parsed.error.issues.map((issue) => `${issue.path.join(".")}: ${issue.message}`).join("; "));
    for (const id of gateIds.slice(1)) put(id, "missing", "Manifest invalid; measurements cannot be qualified.");
    return { schemaVersion: 1, qualified: false, gates };
  }
  const m = parsed.data;
  const refs = new Set(m.evidence.map((e) => e.id));
  const requiredRefs = [m.model.artifactEvidence, m.model.conversionEvidence,
    m.protocol.profileEvidence, m.protocol.preregistrationEvidence, m.protocol.acceptance.reviewEvidence,
    ...[m.model.rights, m.protocol.metricRights, ...m.datasets.map((d) => d.rights)].flatMap((r) => [r.noticeEvidence, r.reviewEvidence]),
    ...[m.independence.evaluation, m.independence.training.sources, m.independence.training.speakers, m.independence.training.noise].flatMap((d) => d.evidenceIds),
    ...Object.values(m.protocol.metricImplementations).map((s) => s.evidenceId),
    ...m.clips.flatMap((c) => [...c.sourceEvidence, c.measurementEvidence, c.outputEvidence]),
    ...(m.runtime ?? []).flatMap((r) => r.evidenceIds),
    ...(m.listening ? [m.listening.protocolEvidence, ...m.listening.trials.map((t) => t.evidenceId)] : [])];
  const unique = (values: string[]) => new Set(values).size === values.length;
  const datasets = new Map(m.datasets.map((d) => [d.id, d]));
  const evidenceHashes = new Map(m.evidence.map((e) => [e.id, e.sha256]));
  // Renaming evidence, dataset or speaker labels must not turn the same source
  // content and segment into an additional independent evaluated fixture.
  const segmentKeys = m.clips.map((c) => JSON.stringify([c.kind,
    [...new Set(c.sourceEvidence.map((id) => evidenceHashes.get(id)))].sort(),
    c.startSample, c.lengthSamples, c.sampleRateHz, c.noiseStartSample, c.mixtureGain, c.snrDb]));
  const validReferences = unique(m.evidence.map((e) => e.id)) && unique(m.datasets.map((d) => d.id)) &&
    unique(m.clips.map((c) => c.id)) && unique(segmentKeys) && requiredRefs.every((ref) => refs.has(ref)) &&
    m.clips.every((c) => datasets.get(c.speechDataset)?.roles.includes("speech") &&
      (c.kind === "clean" || (c.noiseDataset && datasets.get(c.noiseDataset)?.roles.includes("noise") && c.noiseSource && c.noiseClass))) &&
    (!m.listening || m.listening.trials.every((t) => m.clips.some((c) => c.id === t.clipId)));
  check("manifest", !!validReferences, "Unique IDs, resolvable evidence, dataset roles and clip linkage required.");
  const broken: string[] = [];
  if (verify) for (const e of m.evidence) { try { if (!verify(e)) broken.push(e.id); } catch { broken.push(e.id); } }
  if (!verify) put("evidence", "missing", "Local evidence hash verification was not performed.");
  else check("evidence", broken.length === 0, broken.length ? `Missing or mismatched evidence: ${broken.join(", ")}` : "All retained evidence hashes match.");
  const allRights = [m.model.rights, m.protocol.metricRights, ...m.datasets.map((d) => d.rights)];
  check("rights", m.purpose === "production-qualification" && allRights.every((r) => r.evaluationAllowed && r.productionUseAllowed),
    "Production purpose plus explicit evaluation/production rights review for weights, conversion, data and scorers required; private permission cannot qualify.");
  check("independence", [m.independence.evaluation, m.independence.training.sources, m.independence.training.speakers, m.independence.training.noise].every((d) => d.status === "verified"),
    "Evaluation independence and candidate-specific training source/speaker/noise non-overlap must each be verified.");
  const noisy = m.clips.filter((c) => c.kind === "noisy");
  const clean = m.clips.filter((c) => c.kind === "clean");
  check("coverage", noisy.length >= m.protocol.minimumNoisyClips && clean.length >= m.protocol.minimumCleanClips &&
    new Set(noisy.map((c) => c.speaker)).size >= m.protocol.minimumSpeakers &&
    new Set(noisy.map((c) => c.noiseSource)).size >= m.protocol.minimumNoiseSources &&
    m.protocol.requiredNoiseClasses.every((n) => noisy.some((c) => c.noiseClass === n)),
    "All preregistered counts and noise classes required; reused clips are not independent speakers/noise sources.");
  const deltaGate = (id: string, rows: typeof m.clips, before: keyof z.infer<typeof metrics>, after: keyof z.infer<typeof metrics>, threshold: number, regression = false) => {
    const scorerName = { stoi: "STOI", "si-sdr": "SI-SDR", "pesq-clean": "PESQ" }[id];
    if (m.protocol.metricImplementations[id]?.name !== scorerName || !rows.length || rows.some((c) => typeof c.metrics[before] !== "number" || typeof c.metrics[after] !== "number")) {
      put(id, "missing", "Complete per-clip measurements and pinned scorer implementation required."); return;
    }
    const deltas = rows.map((c) => (c.metrics[after] as number) - (c.metrics[before] as number));
    // Contract does not specify a median clean regression: protect every clean fixture.
    const value = regression ? Math.max(...deltas.map((d) => -d)) : median(deltas);
    check(id, regression ? value <= threshold + 1e-12 : value + 1e-12 >= threshold, regression ? `Worst clean PESQ regression <= ${threshold}` : `Median improvement >= ${threshold}`, value);
  };
  deltaGate("stoi", noisy, "stoiBefore", "stoiAfter", 0.03);
  deltaGate("si-sdr", noisy, "siSdrBeforeDb", "siSdrAfterDb", 3);
  deltaGate("pesq-clean", clean, "pesqBefore", "pesqAfter", 0.10, true);
  const rowGate = (id: string, fields: (keyof z.infer<typeof metrics>)[], passed: (c: typeof m.clips[number]) => boolean, detail: string) => {
    if (m.clips.some((c) => fields.some((f) => c.metrics[f] === undefined))) put(id, "missing", `Every clip requires ${fields.join(", ")}.`);
    else check(id, m.clips.every(passed), detail);
  };
  rowGate("clipping", ["introducedClippedSamples", "encodedTruePeakDbtp"], (c) => c.metrics.introducedClippedSamples === 0 && c.metrics.encodedTruePeakDbtp! <= 0,
    "Zero introduced clipped samples and encoded true peak <= 0 dBTP on every fixture.");
  rowGate("loudness", ["integratedLufs", "targetLufs"], (c) => c.metrics.targetLufs === m.protocol.targetLufs && Math.abs(c.metrics.integratedLufs! - c.metrics.targetLufs!) <= 1,
    "Every encoded output within 1 LU of its explicitly approved profile target.");
  rowGate("output-integrity", ["durationValid", "channelsValid", "encodedArtifactValid", "sourceUnchanged"],
    (c) => c.metrics.durationValid === true && c.metrics.channelsValid === true && c.metrics.encodedArtifactValid === true && c.metrics.sourceUnchanged === true,
    "Validated encoded duration/channels, source immutability and final artifact required; preview cannot substitute.");
  const runtime = m.runtime;
  if (!runtime || !["windows", "macos", "linux"].every((p) => runtime.some((r) => r.platform === p))) {
    put("runtime", "missing", "Actual-media CPU app-path offline/cancellation runs on Windows, macOS and Linux required.");
    put("memory", "missing", "Peak memory on each reference platform required.");
  } else {
    const a = m.protocol.acceptance;
    check("runtime", runtime.every((r) => r.actualMedia && r.appPath && r.coldStartOffline && r.cleanupVerified &&
      median(r.warmRtf) <= a.maximumRtf && r.coldLoadMs <= a.maximumColdLoadMs && r.cancellationMs <= a.maximumCancellationMs),
      "Actual-media CPU app runs must meet explicitly reviewed RTF/load/cancel budgets, including cold offline start and cleanup.");
    check("memory", runtime.every((r) => r.peakMemoryMb <= a.maximumPeakMemoryMb), "Peak memory within reviewed budget on all platforms.");
  }
  const l = m.listening;
  if (!l) put("listening", "missing", "Blinded multi-listener speech-damage/artifact assessment absent.");
  else {
    const trialKeys = l.trials.map((t) => `${t.listener}\u0000${t.clipId}`);
    check("listening", l.blinded && l.randomized && l.loudnessMatched && unique(trialKeys) &&
      new Set(l.trials.map((t) => t.listener)).size >= Math.max(2, m.protocol.acceptance.minimumListeners) &&
      l.trials.length >= m.protocol.acceptance.minimumTrials &&
      l.trials.every((t) => !t.speechDamage && !t.unacceptableArtifacts),
      "Unique blinded listener/clip trials, reviewed panel size (at least two), no reported unacceptable speech damage/artifacts.");
  }
  return { schemaVersion: 1, runId: m.runId, qualified: gates.every((g) => g.status === "pass"), gates };
}

export function verifyLocalEvidence(baseDirectory: string) {
  return (e: z.infer<typeof evidence>) => fileSha256(resolve(baseDirectory, e.path)) === e.sha256;
}
